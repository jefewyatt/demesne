#!/usr/bin/env python3
"""Scaffold a new service so it lands on the right machine with the right Komodo config.

Examples:
    # Build from source on the NAS, auto-pick a free host port, app listens on 8080
    python scripts/new_service.py nas recipe-api --build --container-port 8080

    # Prebuilt image on the Orange Pi, explicit host:container port
    python scripts/new_service.py orangepi uptime-kuma --image louislam/uptime-kuma:1.23.16 --port 3001:3001

Creates:
    hosts/<host>/<name>/compose.yaml   (+ Dockerfile and src/ with --build)
    hosts/<host>/<name>/README.md
    komodo/stacks/<host>/<name>.toml

Lines marked TODO(new_service) must be replaced before validate.py will pass.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import PLACEHOLDER, REPO, collect_used_ports, image_is_pinned, load_hosts  # noqa: E402

FIRST_AUTO_PORT = 8100


def pick_port(host: str) -> int:
    used = collect_used_ports(host)
    port = FIRST_AUTO_PORT
    while port in used:
        port += 1
    return port


def main() -> int:
    hosts = load_hosts()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("host", choices=sorted(hosts["hosts"]))
    parser.add_argument("name", help="lowercase letters, digits, dashes; unique across all hosts")
    kind = parser.add_mutually_exclusive_group(required=True)
    kind.add_argument("--build", action="store_true", help="build from source (Dockerfile in the service dir)")
    kind.add_argument("--image", help="prebuilt image with a pinned tag, e.g. nginx:1.28-alpine")
    parser.add_argument("--port", help="HOST:CONTAINER to publish (default: next free host port from 8100)")
    parser.add_argument("--container-port", type=int, default=8080,
                        help="port the app listens on inside the container (default 8080)")
    parser.add_argument("--description", default=f"{PLACEHOLDER}: one-line description")
    args = parser.parse_args()

    name, host = args.name, args.host
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", name):
        parser.error("name must be lowercase letters, digits and dashes")
    for existing in (REPO / "komodo" / "stacks").rglob(f"{name}.toml"):
        parser.error(f"a stack named '{name}' already exists: {existing.relative_to(REPO).as_posix()}")
    svc_dir = REPO / "hosts" / host / name
    if svc_dir.exists():
        parser.error(f"{svc_dir.relative_to(REPO).as_posix()} already exists")
    if args.image:
        pinned, problem = image_is_pinned(args.image)
        if not pinned:
            parser.error(f"image {problem}; pass a pinned tag")

    if args.port:
        host_port, container_port = args.port.split(":", 1)
    else:
        host_port, container_port = str(pick_port(host)), str(args.container_port)

    host_cfg, git = hosts["hosts"][host], hosts["git"]
    appdata = f"{host_cfg['appdata'].rstrip('/')}/{name}"
    strategy = "redeploy-always" if args.build else "redeploy-if-changed"

    image_lines = (f"    build: .\n    image: homelab/{name}:local\n" if args.build
                   else f"    image: {args.image}\n")
    compose = f"""# {name}: {args.description}

services:
  {name}:
{image_lines}    restart: unless-stopped
    ports:
      - "{host_port}:{container_port}"
    # Persistent data goes under ${{APPDATA}} ({appdata} on {host}):
    # volumes:
    #   - ${{APPDATA}}/data:/data
    healthcheck:
      # {PLACEHOLDER}: replace with a command that exits 0 only when the service is healthy,
      # using a tool that exists inside the image (curl, wget, python, the app's own CLI...).
      test: ["CMD", "wget", "-q", "--spider", "http://127.0.0.1:{container_port}/"]
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 15s
"""

    readme = f"""# {name} ({host})

{args.description}

- **URL:** http://{host_cfg['address']}:{host_port}
- **Deploy strategy:** `{strategy}`
- **Secrets:** none  <!-- list each [[SECRET_NAME]] Jeff must create in Komodo -->
- **Persistent data:** none  <!-- or {appdata}/... -->
"""

    build_lines = "# Built from source: build on deploy, never try to `compose pull` our own image.\nrun_build = true\nauto_pull = false\n" if args.build else ""
    toml = f"""# Stack: {name}  →  server: {host}
# Generated by scripts/new_service.py; edit freely, then run scripts/validate.py.

[[stack]]
name = "{name}"
description = "{args.description.replace(chr(92), chr(92) * 2).replace('"', chr(92) + '"')}"
tags = ["git", "{host}", "{strategy}"]

[stack.config]
server = "{host}"
git_provider = "{git['provider']}"
git_https = {str(git['https']).lower()}
git_account = "{git['account']}"
repo = "{git['repo']}"
branch = "{git['branch']}"
run_directory = "hosts/{host}/{name}"
file_paths = ["compose.yaml"]
{build_lines}# Written to .env next to compose.yaml. Secrets go here as [[KOMODO_SECRET_NAME]],
# never as literal values.
environment = \"\"\"
APPDATA = {appdata}
\"\"\"
"""

    svc_dir.mkdir(parents=True)
    (svc_dir / "compose.yaml").write_text(compose, encoding="utf-8", newline="\n")
    (svc_dir / "README.md").write_text(readme, encoding="utf-8", newline="\n")
    if args.build:
        (svc_dir / "src").mkdir()
        (svc_dir / "Dockerfile").write_text(
            f"# {PLACEHOLDER}: replace with a real Dockerfile. Requirements (AGENTS.md):\n"
            f"#   pinned base image tag, non-root USER, app listens on {container_port},\n"
            f"#   and the healthcheck tool used in compose.yaml exists in the image.\n"
            f"# Target arch for this host: {host_cfg['arch']} (it builds natively on {host}).\n"
            f"FROM alpine:3.22\nCOPY src/ /app/\nUSER 10001\nCMD [\"sh\", \"-c\", \"echo replace me; sleep infinity\"]\n",
            encoding="utf-8", newline="\n")
    toml_path = REPO / "komodo" / "stacks" / host / f"{name}.toml"
    toml_path.parent.mkdir(parents=True, exist_ok=True)
    toml_path.write_text(toml, encoding="utf-8", newline="\n")

    created = [svc_dir / "compose.yaml", svc_dir / "README.md", toml_path]
    if args.build:
        created[1:1] = [svc_dir / "Dockerfile", svc_dir / "src/"]
    print("Created:")
    for p in created:
        print(f"  {p.relative_to(REPO).as_posix()}")
    print(f"\nHost port {host_port} -> container port {container_port} on {host} ({host_cfg['arch']}).")
    print(f"Next: replace every {PLACEHOLDER}, then run  python scripts/validate.py")
    return 0


if __name__ == "__main__":
    sys.exit(main())
